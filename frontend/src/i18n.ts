const normalize = (value: string) => value.replace(/\s+/g, " ").trim();

export function translateValue(value: string, lang: Lang): string {
  const normalized = normalize(value);
  if (!normalized) return value;

  const direct = translations[normalized];
  if (direct) return direct[lang];

  const match = Object.values(translations).find(
    (entry) => normalize(entry.ar) === normalized || normalize(entry.en) === normalized
  );

  return match ? match[lang] : value;
}
